// Import only verified, individual vocabulary illustrations. Reader pages stay local.
import fs from 'node:fs';
import path from 'node:path';
import { format } from 'prettier';

const root = path.resolve(process.argv[2] || '../Textbook_Reference/Blue_Sky_Elementary_5');
const catalog = JSON.parse(fs.readFileSync(path.join(root, 'catalog.json'), 'utf8'));
const profiles = {};
const provenance = [];
const slug = (word) =>
  word
    .toLowerCase()
    .replace(/[^a-z]+/g, '-')
    .replace(/^-|-$/g, '');
for (const item of catalog.items) {
  const image = `/assets/vocabulary/g5-unit${item.unit}/${path.basename(item.image)}`;
  const audio = `/assets/words/${slug(item.word)}.wav`;
  fs.mkdirSync(path.dirname('public' + image), { recursive: true });
  fs.copyFileSync(path.join(root, item.image), 'public' + image);
  (profiles[item.unit] ??= []).push({
    word: item.word,
    meaning: item.meaning_ja,
    group: item.group,
    base: '',
    example: item.example,
    image,
    ...(item.pictureEnabled === false ? { pictureEnabled: false } : {}),
    audio: fs.existsSync('public' + audio) ? audio : null,
  });
  provenance.push({
    grade: 5,
    unit: item.unit,
    word: item.word,
    image,
    sourcePage: item.source_page,
    sourceImageSha256: item.image_sha256,
    source: item.source,
    acquisition: item.acquisition,
  });
}
fs.writeFileSync(
  'server/editor/grade5-content.mjs',
  await format(
    '// Generated by scripts/import-grade5.mjs; examples are original classroom prompts.\n' +
      'export const gradeFiveContent = ' +
      JSON.stringify(profiles, null, 2) +
      ';\n',
    { ...JSON.parse(fs.readFileSync('.prettierrc.json', 'utf8')), parser: 'babel' },
  ),
);
fs.writeFileSync(
  'docs/content/grade5-image-sources.json',
  JSON.stringify(
    {
      capturedOn: catalog.capturedOn,
      count: provenance.length,
      note: 'Native reader zoom crops; no upscaling. Full references remain outside public/.',
      units: catalog.units,
      items: provenance,
    },
    null,
    2,
  ) + '\n',
);
console.log('Imported Grade 5:', catalog.units, 'pictures:', provenance.length);
